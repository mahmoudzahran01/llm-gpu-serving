#!/usr/bin/env bash
# Print a kind config for a 1 control-plane + 1 GPU-worker cluster to stdout.
# STATUS: UNTESTED beyond generating/parsing the YAML. On the Spark a NEW kind node cannot boot (uid-0 inotify quota
# exhausted, evidence/20), so this was never applied. It is the design to use once fs.inotify.max_user_instances is raised.
#
# Why this is a script and not a static YAML file: the GPU worker needs the host's NVIDIA driver
# files inside the node container (kind nodes are privileged, so /dev/nvidia* is already visible, but
# the user-space driver libraries are not). We read the list of files from the host CDI spec
# (/var/run/cdi/nvidia.yaml, written by nvidia-ctk) and bind-mount each one at the SAME path, so the
# CDI spec is valid unchanged inside the node. A driver upgrade just means re-running up.sh.
set -euo pipefail
SPEC=${CDI_SPEC:-/var/run/cdi/nvidia.yaml}
HF_DIR=${HF_DIR:-$HOME/.cache/huggingface}
CLUSTER=${CLUSTER:-lab-gpu}
HOST_PORT=${HOST_PORT:-18200}      # vLLM NodePort 30200 is published on 127.0.0.1:$HOST_PORT

[ -r "$SPEC" ] || { echo "missing CDI spec $SPEC (run: sudo nvidia-ctk cdi generate --output=$SPEC)" >&2; exit 1; }

cat <<YAML
# GENERATED by gen-kind-config.sh - do not edit by hand
kind: Cluster
apiVersion: kind.x-k8s.io/v1alpha4
name: $CLUSTER
nodes:
  - role: control-plane
  - role: worker
    kubeadmConfigPatches:
      - |
        kind: JoinConfiguration
        nodeRegistration:
          # GPU nodes are tainted so that ordinary pods do not land on them and eat CPU/RAM that the
          # GPU workload needs; GPU pods carry the matching toleration.
          taints:
            - key: nvidia.com/gpu
              value: present
              effect: NoSchedule
          kubeletExtraArgs:
            # lets the device-plugin DaemonSet affinity (nvidia.com/gpu.present=true) match without NFD
            node-labels: "nvidia.com/gpu.present=true,node-role.lab/gpu=true"
    extraPortMappings:
      - containerPort: 30200        # NodePort of the vllm Service
        hostPort: $HOST_PORT
        listenAddress: "127.0.0.1"
        protocol: TCP
    extraMounts:
      # model weights: already in the host HF cache (some files are root-owned, so read-only)
      - hostPath: $HF_DIR
        containerPath: /hf
        readOnly: true
      # host CDI spec, so the node's containerd also knows the toolkit's device "nvidia.com/gpu=all"
      - hostPath: $SPEC
        containerPath: /etc/cdi/nvidia.yaml
        readOnly: true
      # CDI hooks are executed by runc INSIDE the node, so the hook binary must exist there
      - hostPath: /usr/bin/nvidia-cdi-hook
        containerPath: /usr/bin/nvidia-cdi-hook
        readOnly: true
      - hostPath: /usr/bin/nvidia-ctk
        containerPath: /usr/bin/nvidia-ctk
        readOnly: true
YAML

# every regular file the CDI spec wants to bind-mount into a GPU container (driver libs, nvidia-smi, ...)
awk '/hostPath:/ {print $NF}' "$SPEC" | sort -u | while read -r f; do
  [ -f "$f" ] || continue
  cat <<YAML
      - hostPath: $f
        containerPath: $f
        readOnly: true
YAML
done
